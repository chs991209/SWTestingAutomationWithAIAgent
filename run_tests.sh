#!/bin/bash

echo "========================================"
echo "🚀 AI Agent 기반 자동화: 테스트 실행 시작"
echo "========================================"

# Maven을 사용하여 이전 빌드 찌꺼기를 지우고 테스트 실행
mvn clean test

# 실행 결과(Exit Code)를 캡처하여 성공/실패 여부 자동 판별
RESULT=$?

echo "========================================"
if [ $RESULT -eq 0 ]; then
    echo "✅ 성공: 모든 테스트가 통과되었습니다! (Green)"
    echo "다음 단계: 리팩토링(Refactor) 또는 코드 반영을 진행하세요."
else
    echo "❌ 실패: 하나 이상의 테스트가 실패했습니다. (Red)"
    echo "다음 단계: 실패 로그를 분석하고 구현 코드를 수정하세요."
fi
echo "========================================"

# 스크립트 종료 시 원래의 종료 코드 반환
exit $RESULT